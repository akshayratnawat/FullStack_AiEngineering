"""Chunk the filings in `source_documents`, embed each chunk, store it in `document_chunks`.

Run from the backend folder:
    uv run python ingest/ingest_chunks.py --dry-run                  # chunk only: no API calls, no writes
    uv run python ingest/ingest_chunks.py --accession 0000320193-25-000079 --chunk-index 49
                                                                     # embed + store ONE chunk (the test run)
    uv run python ingest/ingest_chunks.py --accession 0000320193-25-000079   # one whole filing
    uv run python ingest/ingest_chunks.py                            # every filing

Safe to re-run: chunks already stored (same document + chunk_index) are skipped, so
nothing is embedded, or paid for, twice. Use --force to delete and redo.
"""

import argparse
import asyncio
import sys
import uuid
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # so `chunking` imports when run as a script

from chunking import Chunk, chunk_markdown  # noqa: E402

from app.database.supabase import create_service_client  # noqa: E402
from app.embeddings import create_embedding_client, embed_texts  # noqa: E402

EMBED_BATCH = 64  # texts per embeddings request (well under the API's per-request limits)
INSERT_BATCH = 50  # rows per database request (each row carries a 1536-number vector)


def build_row(document: dict, document_id: str, chunk: Chunk, embedding: list[float]) -> dict:
    """Map one chunk onto a `document_chunks` row."""
    return {
        # The Supabase API skips the model's Python-side id default, so we send the id.
        "id": str(uuid.uuid4()),
        "document_id": document_id,
        "chunk_index": chunk.chunk_index,
        "content": chunk.content,
        "page": None,  # filings are HTML, which has no pages
        "section": chunk.section,
        "token_count": chunk.token_count,
        "embedding": embedding,
        # `search_vector` is generated by Postgres from `content`; never sent.
        "chunk_metadata": {
            "ticker": document["ticker"],
            "form": document["form"],
            "fiscal_year": document["fiscal_year"],
            "filing_date": document["filing_date"],
            "accession_number": document["accession_number"],
            "headings": chunk.headings,
        },
    }


async def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--accession", help="only this filing (accession number)")
    parser.add_argument("--chunk-index", type=int, help="only this one chunk of the filing")
    parser.add_argument("--dry-run", action="store_true", help="chunk and report; no API calls, no writes")
    parser.add_argument("--force", action="store_true", help="delete existing chunks and redo them")
    args = parser.parse_args()
    if args.chunk_index is not None and not args.accession:
        parser.error("--chunk-index needs --accession")

    db = await create_service_client()
    query = db.table("source_documents").select(
        "id, ticker, form, fiscal_year, filing_date, accession_number, content_markdown"
    )
    if args.accession:
        query = query.eq("accession_number", args.accession)
    documents = (await query.order("ticker").order("fiscal_year").execute()).data
    if not documents:
        sys.exit("No matching source_documents rows.")

    openai_client = None if args.dry_run else create_embedding_client()
    stored = skipped = tokens_billed = 0

    for document in documents:
        label = f"{document['ticker']} FY{document['fiscal_year']} {document['accession_number']}"
        chunks = chunk_markdown(document["content_markdown"], name=f"{document['accession_number']}.md")
        if args.chunk_index is not None:
            chunks = [c for c in chunks if c.chunk_index == args.chunk_index]
            if not chunks:
                sys.exit(f"{label}: no chunk with index {args.chunk_index}.")

        if args.dry_run:
            sizes = [c.token_count for c in chunks]
            print(f"{label}: {len(chunks)} chunks, {sum(sizes):,} tokens, max {max(sizes)}, "
                  f"{sum(1 for c in chunks if c.section)} with a section")
            continue

        if args.force:
            delete = db.table("document_chunks").delete().eq("document_id", document["id"])
            if args.chunk_index is not None:
                delete = delete.eq("chunk_index", args.chunk_index)
            await delete.execute()
        existing = await (
            db.table("document_chunks").select("chunk_index").eq("document_id", document["id"]).execute()
        )
        done = {row["chunk_index"] for row in existing.data}
        todo = [c for c in chunks if c.chunk_index not in done]
        skipped += len(chunks) - len(todo)

        for start in range(0, len(todo), EMBED_BATCH):
            batch = todo[start : start + EMBED_BATCH]
            vectors, billed = await embed_texts(openai_client, [c.content for c in batch])
            tokens_billed += billed
            rows = [build_row(document, document["id"], c, v) for c, v in zip(batch, vectors, strict=True)]
            for i in range(0, len(rows), INSERT_BATCH):
                await db.table("document_chunks").insert(rows[i : i + INSERT_BATCH]).execute()
            stored += len(batch)
        print(f"{label}: stored {len(todo)} chunks, skipped {len(chunks) - len(todo)} already stored")

    if args.dry_run:
        return
    total = await db.table("document_chunks").select("id", count="exact").limit(1).execute()
    print(f"\nStored {stored}, skipped {skipped}, tokens billed {tokens_billed:,}. "
          f"Rows now in document_chunks: {total.count}")


if __name__ == "__main__":
    asyncio.run(main())
